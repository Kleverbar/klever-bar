// Ждем загрузки страницы
document.addEventListener('DOMContentLoaded', function() {
    console.log('grunty.js загружен');
    
    // Проверяем, что модальное окно доступно
    if (typeof window.openProductModal !== 'function') {
        console.error('Функция openProductModal не найдена! Проверьте подключение modal.js');
        return;
    }
    
    // Находим все карточки товаров
    const productCards = document.querySelectorAll('.product-card');
    console.log('Найдено карточек товаров:', productCards.length);
    
    if (productCards.length === 0) {
        console.warn('Карточки товаров не найдены! Проверьте класс product-card в HTML');
        return;
    }
    
    // Добавляем обработчик на каждую карточку
    productCards.forEach((card, index) => {
        // Добавляем курсор-указатель
        card.style.cursor = 'pointer';
        
        card.addEventListener('click', function(event) {
            // Предотвращаем всплытие события
            event.preventDefault();
            event.stopPropagation();
            
            // Получаем ID товара из data-атрибута
            const productId = this.dataset.productId;
            console.log(`Клик по карточке #${index + 1}, productId:`, productId);
            
            if (!productId) {
                console.error('У карточки отсутствует data-product-id');
                alert('Ошибка: идентификатор товара не найден');
                return;
            }
            
            // Ищем данные о товаре
            const product = productData[productId];
            
            if (product) {
                console.log('Данные найдены, открываем модальное окно для:', product.title);
                window.openProductModal(product);
            } else {
                console.error('Товар с ID "' + productId + '" не найден в productData');
                alert('Информация о товаре временно недоступна');
            }
        });
    });
});